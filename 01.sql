-- 1021 Creative POC: foundation objects (roles, warehouses, databases, schemas)
-- Run as ACCOUNTADMIN. Idempotent.

USE ROLE ACCOUNTADMIN;

-- Roles
CREATE ROLE IF NOT EXISTS POC_1021_ADMIN   COMMENT = 'Owns and builds all POC_1021 objects';
CREATE ROLE IF NOT EXISTS POC_1021_ANALYST COMMENT = 'Read access to SILVER and GOLD';

GRANT ROLE POC_1021_ANALYST TO ROLE POC_1021_ADMIN;
GRANT ROLE POC_1021_ADMIN   TO ROLE SYSADMIN;
GRANT ROLE POC_1021_ADMIN   TO USER CLUGG_SFC;

-- Admin needs these to build pipelines and accept marketplace listings later
GRANT EXECUTE TASK ON ACCOUNT          TO ROLE POC_1021_ADMIN;
GRANT EXECUTE MANAGED TASK ON ACCOUNT  TO ROLE POC_1021_ADMIN;
GRANT IMPORT SHARE ON ACCOUNT          TO ROLE POC_1021_ADMIN;
GRANT CREATE DATABASE ON ACCOUNT       TO ROLE POC_1021_ADMIN;

-- Warehouses
CREATE WAREHOUSE IF NOT EXISTS POC_1021_INGEST_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'API ingestion and pipeline tasks';
CREATE WAREHOUSE IF NOT EXISTS POC_1021_ANALYST_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Analyst queries and dashboards';

GRANT OWNERSHIP ON WAREHOUSE POC_1021_INGEST_WH  TO ROLE POC_1021_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON WAREHOUSE POC_1021_ANALYST_WH TO ROLE POC_1021_ADMIN COPY CURRENT GRANTS;
GRANT USAGE ON WAREHOUSE POC_1021_ANALYST_WH TO ROLE POC_1021_ANALYST;

-- Databases and schemas (one schema per source in each layer)
USE ROLE POC_1021_ADMIN;

CREATE DATABASE IF NOT EXISTS POC_1021_BRONZE COMMENT = 'Raw landed data, one schema per source';
CREATE DATABASE IF NOT EXISTS POC_1021_SILVER COMMENT = 'Cleaned, typed data, one schema per source';
CREATE DATABASE IF NOT EXISTS POC_1021_GOLD   COMMENT = 'Business-ready models (later)';

CREATE SCHEMA IF NOT EXISTS POC_1021_BRONZE.TUBULAR;
CREATE SCHEMA IF NOT EXISTS POC_1021_BRONZE.MELTWATER;
CREATE SCHEMA IF NOT EXISTS POC_1021_BRONZE.MARKETPLACE;
CREATE SCHEMA IF NOT EXISTS POC_1021_SILVER.TUBULAR;
CREATE SCHEMA IF NOT EXISTS POC_1021_SILVER.MELTWATER;
CREATE SCHEMA IF NOT EXISTS POC_1021_SILVER.MARKETPLACE;
CREATE SCHEMA IF NOT EXISTS POC_1021_GOLD.TUBULAR;
CREATE SCHEMA IF NOT EXISTS POC_1021_GOLD.MELTWATER;
CREATE SCHEMA IF NOT EXISTS POC_1021_GOLD.MARKETPLACE;

-- Analyst read access on SILVER and GOLD (current + future)
GRANT USAGE ON DATABASE POC_1021_SILVER TO ROLE POC_1021_ANALYST;
GRANT USAGE ON DATABASE POC_1021_GOLD   TO ROLE POC_1021_ANALYST;
GRANT USAGE ON ALL SCHEMAS IN DATABASE POC_1021_SILVER TO ROLE POC_1021_ANALYST;
GRANT USAGE ON ALL SCHEMAS IN DATABASE POC_1021_GOLD   TO ROLE POC_1021_ANALYST;

USE ROLE ACCOUNTADMIN;  -- future grants at database level need MANAGE GRANTS
GRANT USAGE  ON FUTURE SCHEMAS IN DATABASE POC_1021_SILVER TO ROLE POC_1021_ANALYST;
GRANT USAGE  ON FUTURE SCHEMAS IN DATABASE POC_1021_GOLD   TO ROLE POC_1021_ANALYST;
GRANT SELECT ON FUTURE TABLES  IN DATABASE POC_1021_SILVER TO ROLE POC_1021_ANALYST;
GRANT SELECT ON FUTURE VIEWS   IN DATABASE POC_1021_SILVER TO ROLE POC_1021_ANALYST;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN DATABASE POC_1021_SILVER TO ROLE POC_1021_ANALYST;
GRANT SELECT ON FUTURE TABLES  IN DATABASE POC_1021_GOLD   TO ROLE POC_1021_ANALYST;
GRANT SELECT ON FUTURE VIEWS   IN DATABASE POC_1021_GOLD   TO ROLE POC_1021_ANALYST;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN DATABASE POC_1021_GOLD   TO ROLE POC_1021_ANALYST;




