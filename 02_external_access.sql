-- 1021 Creative POC: external access for Tubular and Meltwater APIs
-- Secret values are NOT stored here. Set them with:
--   ALTER SECRET POC_1021_BRONZE.TUBULAR.TUBULAR_API_KEY     SET SECRET_STRING = '<key>';
--   ALTER SECRET POC_1021_BRONZE.MELTWATER.MELTWATER_API_KEY SET SECRET_STRING = '<key>';

USE ROLE POC_1021_ADMIN;

CREATE NETWORK RULE IF NOT EXISTS POC_1021_BRONZE.TUBULAR.TUBULAR_API_RULE
  MODE = EGRESS TYPE = HOST_PORT VALUE_LIST = ('tubularlabs.com:443');
CREATE NETWORK RULE IF NOT EXISTS POC_1021_BRONZE.MELTWATER.MELTWATER_API_RULE
  MODE = EGRESS TYPE = HOST_PORT VALUE_LIST = ('api.meltwater.com:443');

CREATE SECRET IF NOT EXISTS POC_1021_BRONZE.TUBULAR.TUBULAR_API_KEY
  TYPE = GENERIC_STRING SECRET_STRING = 'SET_ME';
CREATE SECRET IF NOT EXISTS POC_1021_BRONZE.MELTWATER.MELTWATER_API_KEY
  TYPE = GENERIC_STRING SECRET_STRING = 'SET_ME';

USE ROLE ACCOUNTADMIN;

CREATE EXTERNAL ACCESS INTEGRATION IF NOT EXISTS POC_1021_TUBULAR_EAI
  ALLOWED_NETWORK_RULES = (POC_1021_BRONZE.TUBULAR.TUBULAR_API_RULE)
  ALLOWED_AUTHENTICATION_SECRETS = (POC_1021_BRONZE.TUBULAR.TUBULAR_API_KEY)
  ENABLED = TRUE;
CREATE EXTERNAL ACCESS INTEGRATION IF NOT EXISTS POC_1021_MELTWATER_EAI
  ALLOWED_NETWORK_RULES = (POC_1021_BRONZE.MELTWATER.MELTWATER_API_RULE)
  ALLOWED_AUTHENTICATION_SECRETS = (POC_1021_BRONZE.MELTWATER.MELTWATER_API_KEY)
  ENABLED = TRUE;

GRANT USAGE ON INTEGRATION POC_1021_TUBULAR_EAI   TO ROLE POC_1021_ADMIN;
GRANT USAGE ON INTEGRATION POC_1021_MELTWATER_EAI TO ROLE POC_1021_ADMIN;
